import fs from 'node:fs'
const root=new URL('../',import.meta.url)
const templates=JSON.parse(fs.readFileSync(new URL('src/registry/templates.json',root)))
const motions=JSON.parse(fs.readFileSync(new URL('src/registry/motions.json',root)))
const campaigns=JSON.parse(fs.readFileSync(new URL('src/registry/campaigns.json',root)))
const tc=templates.map(t=>({id:t.id,name:t.name,type:t.type,subtype:t.subtype,format:t.format,status:t.status,tags:t.tags,recipe:t.recipe,pack:t.pack,implementation:t.implementation,...(t.duration?{duration:t.duration}:{})}))
const mc=motions.map(m=>({id:m.id,name:m.name,engine:m.engine,category:m.category,intensity:m.intensity,tags:m.tags,bestFor:m.bestFor}))
const cc=campaigns.map(c=>({id:c.id,name:c.name,status:c.status,tags:c.tags,templates:c.templates}))
fs.writeFileSync(new URL('claude/catalog.compact.json',root),JSON.stringify(tc))
fs.writeFileSync(new URL('claude/motions.compact.json',root),JSON.stringify(mc))
fs.writeFileSync(new URL('claude/campaigns.compact.json',root),JSON.stringify(cc))
console.log('compact catalogs rebuilt')
